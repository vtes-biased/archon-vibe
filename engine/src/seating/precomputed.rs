/// Convert precomputed index-based seating to named players
pub(crate) fn apply_precomputed(
    players: &[String],
    precomputed: &[Vec<Vec<usize>>],
) -> Vec<Vec<Vec<String>>> {
    precomputed
        .iter()
        .map(|round| {
            round
                .iter()
                .map(|table| table.iter().map(|&idx| players[idx].clone()).collect())
                .collect()
        })
        .collect()
}
